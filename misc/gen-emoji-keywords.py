"""Regenerates src/core/ngosen-emoji-keywords.inc from data/emoji-keywords.tsv and the CLDR country
names (Fedora: cldr-emoji-annotation; Debian: unicode-cldr-core), and the emoji list the settings
window shows from Unicode's emoji-test.txt (Fedora: unicode-emoji; Debian: unicode-data).

A flag has only the keyword "flag" in CLDR; its country name is in the spoken name, "flag: Vietnam".
"""

import os
import re
import subprocess
import sys
import tempfile
import unicodedata
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CLDR = Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/unicode/cldr/common")
EMOJI_TEST = Path(sys.argv[2] if len(sys.argv) > 2 else "/usr/share/unicode/emoji/emoji-test.txt")
OUT = ROOT / "src/core/ngosen-emoji-keywords.inc"
TABLE = ROOT / "settings-gui/core/emoji_table.py"
# Newer emoji show as boxes with the emoji fonts most users have.
NEWEST = 16.0
SKIN_TONES = {chr(c) for c in range(0x1F3FB, 0x1F400)}
# An English keyword shared by more emoji than this names none of them, as man, hand or face do.
MOST_EMOJI = 20
# The list shows five; the rest of a keyword's emoji would never be offered.
SHOWN = 5


def is_flag(cp):
    return len(cp) == 2 and all(0x1F1E6 <= ord(c) <= 0x1F1FF for c in cp)


def literal(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    rows, seen = [], set()
    for line in (ROOT / "data/emoji-keywords.tsv").read_text(encoding="utf-8").splitlines():
        # Yahoo codes such as #-o start with #, so a comment is a line without tabs.
        if not line or (line.startswith("#") and "\t" not in line):
            continue
        keyword, emoji, kind = line.split("\t")
        rows.append((keyword, emoji, kind))
        seen.add(keyword)
    for lang in ("vi", "en"):
        for node in ET.parse(CLDR / "annotationsDerived" / f"{lang}.xml").iter("annotation"):
            cp = node.get("cp")
            if node.get("type") != "tts" or not is_flag(cp):
                continue
            name = unicodedata.normalize("NFC", node.text.split(": ", 1)[-1].lower())
            if name not in seen:
                seen.add(name)
                rows.append((name, cp, "country"))
    rows += english_rows(seen)
    rows.sort()
    # The settings window turns a pair off by the emoji as written, so each needs the one spelling.
    used = {e for _k, emoji, _kind in rows for e in emoji.split()}
    if unknown := sorted(e for e in used if e not in versions()):
        sys.exit(f"not a fully-qualified emoji: {' '.join(unknown)}")
    if too_new := sorted(e for e in used if versions()[e] > NEWEST):
        sys.exit(f"newer than Emoji {NEWEST}: {' '.join(too_new)}")
    with OUT.open("w", encoding="utf-8") as f:
        f.write(
            "// Generated by misc/gen-emoji-keywords.py; edit data/emoji-keywords.tsv instead.\n"
        )
        for keyword, emoji, kind in rows:
            f.write(f"{{{literal(keyword)}, {literal(emoji)}, EmojiKind::{kind.capitalize()}}},\n")
    print(f"{len(rows)} keywords written to {OUT.relative_to(ROOT)}")
    write_table(rows)


_versions = {}


def versions():
    """The Emoji version each emoji came with."""
    if not _versions:
        for line in EMOJI_TEST.read_text(encoding="utf-8").splitlines():
            if "; fully-qualified" in line:
                emoji = "".join(chr(int(c, 16)) for c in line.split(";")[0].split())
                _versions[emoji] = float(line.split("#", 1)[1].split()[1].lstrip("E"))
    return _versions


def english_rows(seen):
    """CLDR's English keywords and names, for emoji the settings window lists.

    An emoji whose name is the keyword, or ends with it, comes first, then Unicode's order.
    """
    order = {bare(e): i for i, e in enumerate(versions())}
    full = {bare(e): e for e in versions()}
    names, emoji_of = {}, {}
    for folder in ("annotations", "annotationsDerived"):
        for node in ET.parse(CLDR / folder / "en.xml").iter("annotation"):
            key = bare(node.get("cp"))
            if key not in full or versions()[full[key]] > NEWEST or SKIN_TONES & set(key):
                continue
            text = node.text.strip().lower()
            words = [text] if node.get("type") == "tts" else text.split("|")
            if node.get("type") == "tts":
                names[key] = text
            for word in (w.strip() for w in words):
                if is_english(word):
                    emoji_of.setdefault(word, set()).add(key)
    rows = []
    for word, keys in emoji_of.items():
        # hahaha or zzz is a sound, and those are picked by hand.
        if word in seen or len(keys) > MOST_EMOJI or re.fullmatch(r"(..?)\1+", word):
            continue
        best = sorted(keys, key=lambda k: (rank(names.get(k, ""), word), order[k]))[:SHOWN]
        rows.append((word, " ".join(full[k] for k in best), "english"))
    return rows


def rank(name, word):
    # moon offers the new moon before the moon cake.
    if name == word:
        return 0
    if name.endswith(" " + word):
        return 1
    return 2 if word in name.split() else 3


def is_english(text):
    # Only what a keyboard types as is; a name like "flag: Vietnam" or "piñata" is not.
    return is_word(text) and all(c.isascii() and (c.isalnum() or c in " -'") for c in text)


def is_word(text):
    # A spoken name such as "mặt cười miệng há với mắt to" or "cờ: việt nam" is nothing anyone types.
    return bool(text) and ":" not in text and len(text.split()) <= 3


def bare(emoji):
    return emoji.replace("\ufe0f", "")


def vietnamese_phrases(phrases):
    """The phrases the engine reads as Vietnamese, asked of the engine itself."""
    with tempfile.NamedTemporaryFile("w", suffix=".txt", encoding="utf-8") as file:
        file.write("\n".join(sorted(set(phrases))) + "\n")
        file.flush()
        result = subprocess.run(
            [
                "cargo",
                "test",
                "--lib",
                "print_vietnamese_phrases",
                "--",
                "--ignored",
                "--nocapture",
            ],
            cwd=ROOT / "bamboo-rs",
            env={**os.environ, "NGOSEN_WORDS": file.name},
            text=True,
            capture_output=True,
            check=True,
        )
    return {
        line.split("\t", 1)[1]
        for line in result.stdout.splitlines()
        if line.startswith("VIETNAMESE\t")
    }


def write_table(rows):
    """The settings window's list: every emoji, its group, spoken name and keywords.

    "on" are the keywords that offer it by default; "off" are other words of its CLDR name the user
    can turn on with one click; "english" are the English keywords, behind their own switch.
    """
    on, english, english_off = {}, {}, {}
    # The engine skips an English keyword typed as Vietnamese (can, me, no), so it starts off and
    # turns on as the user's own word.
    vietnamese = vietnamese_phrases(k for k, _e, kind in rows if kind == "english")
    for keyword, emoji, kind in rows:
        for e in emoji.split():
            if kind != "english":
                target = on
            else:
                target = english_off if keyword in vietnamese else english
            target.setdefault(bare(e), []).append(keyword)
    names, words = {}, {}
    for folder in ("annotations", "annotationsDerived"):
        for node in ET.parse(CLDR / folder / "vi.xml").iter("annotation"):
            cp = bare(node.get("cp"))
            text = unicodedata.normalize("NFC", node.text.strip().lower())
            if node.get("type") == "tts":
                names[cp] = text
            else:
                words[cp] = [w.strip() for w in text.split("|") if w.strip()]
    groups, table, group = [], [], None
    for line in EMOJI_TEST.read_text(encoding="utf-8").splitlines():
        if line.startswith("# group:"):
            group = line.split(":", 1)[1].strip()
            if group != "Component":
                groups.append(group)
            continue
        if "; fully-qualified" not in line or group == "Component":
            continue
        emoji = "".join(chr(int(c, 16)) for c in line.split(";")[0].split())
        version = float(line.split("#", 1)[1].split()[1].lstrip("E"))
        if version > NEWEST or SKIN_TONES & set(emoji):
            continue
        key = bare(emoji)
        defaults = sorted(set(on.get(key, [])))
        others = [
            w
            for w in dict.fromkeys(
                [names.get(key, ""), *words.get(key, []), *sorted(english_off.get(key, []))]
            )
            if is_word(w) and w not in defaults
        ]
        table.append(
            (
                emoji,
                groups.index(group),
                names.get(key, ""),
                tuple(defaults),
                tuple(others),
                tuple(sorted(set(english.get(key, [])))),
            )
        )
    with TABLE.open("w", encoding="utf-8") as f:
        f.write(
            "# Generated by misc/gen-emoji-keywords.py; edit data/emoji-keywords.tsv instead.\n"
        )
        f.write("# fmt: off\n")
        f.write(f"GROUPS = {tuple(groups)!r}\n")
        f.write(
            "# (emoji, group, name, keywords on by default, other words of its name, English keywords)\n"
        )
        f.write("EMOJI = (\n")
        for row in table:
            f.write(f"    {row!r},\n")
        f.write(")\n")
    print(f"{len(table)} emoji written to {TABLE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
